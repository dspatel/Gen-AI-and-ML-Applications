def get_llm():
    model_id = 'mistralai/mistral-small-3-1-24b-instruct-2503' # Specify the Mixtral 8x7B model
    
    parameters = {
        GenParams.MAX_NEW_TOKENS: 256,  # this controls the maximum number of tokens in the generated output
        GenParams.TEMPERATURE: 0.5, # this randomness or creativity of the model's responses
    }
    
    project_id = "skills-network"
    
    watsonx_llm = WatsonxLLM(
        model_id=model_id,
        url="https://us-south.ml.cloud.ibm.com",
        params=parameters,
        project_id=project_id
    )
    
    
    return watsonx_llm
##Document loader
def document_loader(file_path):
    loader = PyPDFLoader(file_path)
    pages = loader.load()
    return pages

##Text Splitter
def text_splitter(pages):
    text_splitter = RecursiveCharacterTextSplitter(
        chunk_size=1000,
        chunk_overlap=20,
        length_function=len
    )
    docs = text_splitter.split_documents(pages)
    return docs



#use the IMB Slate 125M embedding model
def watsonx_embedding():
    embed_params = {
        EmbedTextParamsMetaNames.TRUNCATE_INPUT_TOKENS: 3,
        EmbedTextParamsMetaNames.RETURN_OPTIONS: {"input_text": True},
    }

    watsonx_embedding = WatsonxEmbeddings(
        model_id=  "ibm/slate-125m-english-rtrvr-v2" ,  # Specify IBM's Granite embedding model
        url="https://us-south.ml.cloud.ibm.com",
        project_id="skills-network",
        params=embed_params,
    )
    
    return watsonx_embedding

##Vector Database
def vector_database(chunks):
    watsonx_embed = watsonx_embedding()
    
    vectordb = Chroma.from_documents(chunks, watsonx_embed)
    return vectordb

##Retriever
def retriever(file):
    pages = document_loader(file)
    chunks = text_splitter(pages)
    vectordb = vector_database(chunks)
    retriever = vectordb.as_retriever()
    return vectordb


#QA Chain to get answers from the documents

def retriever_qa(file, query):
    llm = get_llm()
    retriever_obj = retriever(file)
    qa = RetrievalQA.from_chain_type(llm=llm, 
                                    chain_type="stuff", 
                                    retriever=retriever_obj, 
                                    return_source_documents=True)
    response = qa.invoke(query)
    return response['result']
